// Bakes the vendored game enums (data/enums.ts) into a static TS module for
// the React frontend, so enum dropdowns render with zero IPC round-trips.
//
// The enums only change when the game updates and you re-run
// `npm run vendor:types` — after that, re-run `npm run enums` to refresh the
// snapshot. Enums missing from the snapshot (stale bake) fall back to the
// docs:field "__probe__" IPC lookup at runtime, same as the vanilla renderer.
//
// Usage: npm run enums
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "data", "enums.ts");
const DEST = path.join(__dirname, "..", "frontend", "src", "api", "enums.generated.ts");

function parse(src) {
  const out = {};
  const enumRe = /export enum (EGame[A-Za-z0-9_]+)\s*\{([^}]*)\}/gs;
  let m;
  while ((m = enumRe.exec(src)) !== null) {
    const name = m[1];
    const members = [];
    const memRe = /^\s*([A-Za-z0-9_]+)\s*=\s*(-?\d+)/gm;
    let mm;
    while ((mm = memRe.exec(m[2])) !== null) members.push({ name: mm[1], value: Number(mm[2]) });
    if (members.length) out[name] = members;
  }
  return out;
}

function main() {
  if (!fs.existsSync(SRC)) {
    console.warn(`[enums] ${SRC} not found — writing empty snapshot (runtime IPC probe will be used).`);
    fs.writeFileSync(
      DEST,
      `// AUTO-GENERATED by scripts/export-frontend-enums.js — do not edit.\n` +
        `// Source data/enums.ts was MISSING at generation time.\n` +
        `export const ENUM_MEMBERS: Record<string, Array<{ name: string; value: number }>> = {};\n` +
        `export const ENUM_GENERATED_AT: string | null = null;\n`,
    );
    return;
  }
  const map = parse(fs.readFileSync(SRC, "utf8"));
  const names = Object.keys(map).sort();
  const body =
    `// AUTO-GENERATED by scripts/export-frontend-enums.js — do not edit.\n` +
    `// Source: data/enums.ts (${names.length} enums). Regenerate: npm run enums\n` +
    `export const ENUM_MEMBERS: Record<string, Array<{ name: string; value: number }>> = ${JSON.stringify(map, null, 2)};\n` +
    `export const ENUM_GENERATED_AT: string | null = ${JSON.stringify(new Date().toISOString())};\n`;
  fs.mkdirSync(path.dirname(DEST), { recursive: true });
  fs.writeFileSync(DEST, body);
  const members = names.reduce((n, k) => n + map[k].length, 0);
  console.log(`[enums] baked ${names.length} enums, ${members} members → ${path.relative(process.cwd(), DEST)}`);
}

main();
